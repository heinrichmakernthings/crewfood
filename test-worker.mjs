import assert from 'node:assert/strict';
import worker from './src/worker.js';
const env = {SITE_PASSWORD: 'correct horse battery', ASSETS: {fetch: async () => new Response('<h1>app</h1>')}};
const basic = (u, p) => ({headers: {Authorization: 'Basic ' + Buffer.from(u + ':' + p).toString('base64')}});
const call = (e, init) => worker.fetch(new Request('https://x.test/', init), e);
assert.equal((await call(env)).status, 401, 'no password asks for one');
assert.ok((await call(env)).headers.get('WWW-Authenticate').startsWith('Basic'));
assert.equal((await call(env, basic('anyone', 'wrong'))).status, 401, 'wrong password refused');
const ok = await call(env, basic('anyone', 'correct horse battery'));
assert.equal(ok.status, 200);
assert.equal(await ok.text(), '<h1>app</h1>');
assert.ok(ok.headers.get('Cache-Control').includes('no-store'));
assert.equal((await call(env, basic('x', 'correct horse battery:extra'))).status, 401);
assert.equal((await call({...env, SITE_PASSWORD: 'pa:ss'}, basic('u', 'pa:ss'))).status, 200, 'colon in password works');
assert.equal((await call({...env, SITE_PASSWORD: 'pässwörd €'}, basic('u', 'pässwörd €'))).status, 200, 'non-ASCII password works');
assert.equal((await call({ASSETS: env.ASSETS}, basic('u', ''))).status, 503, 'no secret set means closed');
assert.equal((await call({...env, SITE_USER: 'sam'}, basic('bob', 'correct horse battery'))).status, 401, 'username enforced when set');
assert.equal((await call({...env, SITE_USER: 'sam'}, basic('sam', 'correct horse battery'))).status, 200);
assert.equal((await call(env, {headers: {Authorization: 'Basic %%%'}})).status, 401, 'garbage header refused');
console.log('worker tests passed');
